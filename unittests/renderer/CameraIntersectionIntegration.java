package renderer;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.util.List;

import geometries.impl.Plane;
import geometries.impl.Sphere;
import geometries.impl.Triangle;
import org.junit.jupiter.api.Test;

import geometries.api.Intersectable;
import primitives.Point;
import primitives.Ray;
import primitives.Vector;

/**
 * Integration tests for {@link Camera} ray construction and geometry intersections.
 * <p>
 * The tests verify:
 * </p>
 * <ul>
 * <li>Integration of camera ray generation with Sphere intersections</li>
 * <li>Integration of camera ray generation with Plane intersections</li>
 * <li>Integration of camera ray generation with Triangle intersections</li>
 * </ul>
 * * @author ityy35-bit
 */
public class CameraIntersectionIntegration {

    /** Default constructor to satisfy documentation tools. */
    CameraIntersectionIntegration() { /* Default constructor to satisfy documentation tools */ }

    /**
     * Helper method to assert the total number of intersections across all rays
     * generated by a camera through a 3x3 view plane against a given geometry.
     * @param camera   the configured camera (must be set to 3x3 resolution)
     * @param geometry the geometric body to intersect with the rays
     * @param expectedIntersects the expected total number of intersections
     * @param testName the name of the test for the assertion failure message
     */
    private void assertIntersectionsCount(Camera camera, Intersectable geometry, int expectedIntersects, String testName){
        int count = 0;

        for (int i = 0; i < 3; ++i) {
            for (int j = 0; j < 3; ++j) {
                Ray ray = camera.constructRay(j, i);
                List<Point> intersections = geometry.findIntersections(ray);

                if (intersections != null) {
                    count += intersections.size();
                }
            }
        }

        assertEquals(expectedIntersects, count, testName);
    }

    Camera camera1 = Camera.getBuilder()
            .setLocation(new Point(0, 0, 0.5))
            .setDirection(new Vector(0, 0, -1), new Vector(0, 1, 0))
            .setVpDistance(1d)
            .setVpSize(3d, 3d)
            .setResolution(3, 3)
            .build();

    Camera camera2 = Camera.getBuilder()
            .setLocation(Point.ZERO)
            .setDirection(new Vector(0, 0, -1), new Vector(0, 1, 0))
            .setVpDistance(1d)
            .setVpSize(3d, 3d)
            .setResolution(3, 3)
            .build();

    /**
     * Integration tests for Camera and Sphere intersections.
     */
    @Test
    void testCameraRaySphereIntegration() {
        // TC01: Sphere r=1 (2 intersections)
        Sphere sphere1 = new Sphere(new Point(0, 0, -3), 1d);
        assertIntersectionsCount(camera1, sphere1, 2, "Sphere TC01: 2 intersections");
        // TC02: Sphere r=2.5 (18 intersections)
        Sphere sphere2 = new Sphere(new Point(0, 0, -2.5), 2.5d);
        assertIntersectionsCount(camera1, sphere2, 18, "Sphere TC02: 18 intersections");
        // TC03: Sphere r=2 (10 intersections)
        Sphere sphere3 = new Sphere(new Point(0, 0, -2), 2d);
        assertIntersectionsCount(camera1, sphere3, 10, "Sphere TC03: 10 intersections");
        // TC04: Sphere r=4 (9 intersections)
        Sphere sphere4 = new Sphere(new Point(0, 0, -1), 4d);
        assertIntersectionsCount(camera2, sphere4, 9, "Sphere TC04: 9 intersections");
        // TC01: Sphere r=0.5 (0 intersections)
        Sphere sphere5 = new Sphere(new Point(0, 0, 1), 0.5d);
        assertIntersectionsCount(camera2, sphere5, 0, "Sphere TC05: 0 intersections");
    }

    /**
     * Integration tests for Camera and Plane intersections.
     */
    @Test
    void testCameraRayPlaneIntegration() {
        // TC01: Plane is parallel to the View Plane (9 intersections)
        Plane plane1 = new Plane(new Point(0, 0, -5), new Vector(0, 0, 1));
        assertIntersectionsCount(camera2, plane1, 9, "Plane TC01: 9 intersections");

        // TC02: Plane is slightly tilted (9 intersections)
        Plane plane2 = new Plane(new Point(0, 0, -5), new Vector(0, 1, 2));
        assertIntersectionsCount(camera2, plane2, 9, "Plane TC02: 9 intersections");

        // TC03: Plane is severely tilted (6 intersections)
        Plane plane3 = new Plane(new Point(0, 0, -5), new Vector(0, 1, 1));
        assertIntersectionsCount(camera2, plane3, 6, "Plane TC03: 6 intersections");
    }

    /**
     * Integration tests for Camera and Triangle intersections.
     */
    @Test
    void testCameraRayTriangleIntegration() {
        // TC01: Small triangle (1 intersection)
        Triangle triangle1 = new Triangle(
                new Point(0, 1, -2),
                new Point(1, -1, -2),
                new Point(-1, -1, -2));
        assertIntersectionsCount(camera2, triangle1, 1, "Triangle TC01: 1 intersection");

        // TC02: Tall triangle (2 intersections)
        Triangle triangle2 = new Triangle(
                new Point(0, 20, -2),
                new Point(1, -1, -2),
                new Point(-1, -1, -2));
        assertIntersectionsCount(camera2, triangle2, 2, "Triangle TC02: 2 intersections");
    }
}
