package showcase;

import geometries.impl.Plane;
import geometries.impl.Polygon;
import geometries.impl.Sphere;
import lighting.AmbientLight;
import lighting.PointLight;
import lighting.SpotLight;
import org.junit.jupiter.api.Test;
import primitives.Color;
import primitives.Double3;
import primitives.Material;
import primitives.Point;
import primitives.Vector;
import renderer.Camera;
import renderer.RayTracerType;
import renderer.postprocessing.BloomFilter;
import renderer.sampling.Jittered;
import scene.Scene;
import showcase.ChessPieces.Piece;

import java.util.Random;

/**
 * A showcase of glass: a chess endgame in crystal and smoked glass, with depth of field, soft
 * shadows and studio lighting. Every object in it is generated by code.
 *
 * @author itzik123
 */
@Showcase
class ChessShowcaseTest {

    /** Default constructor to satisfy JavaDoc generator */
    ChessShowcaseTest() { /* to satisfy JavaDoc generator */ }

    /** The width of a board square */
    private static final double SQUARE = 100;
    /** Pieces float this far above the board, so their bases never coincide with it */
    private static final double LIFT = 0.2;
    /** The glass of the white pieces: clear crystal */
    private static final Material CRYSTAL = new Material().setKs(0.9).setShininess(1200)
            .setKt(new Double3(0.94, 0.95, 0.97)).setIor(1.52);
    /** The glass of the black pieces: smoked */
    private static final Material SMOKED_GLASS = new Material().setKs(0.9).setShininess(1200)
            .setKt(new Double3(0.55, 0.46, 0.37)).setIor(1.52);
    /** Warm colors of the out-of-focus lights in the background */
    private static final Color[] BOKEH_COLORS = {new Color(255, 170, 70), new Color(255, 205, 120),
            new Color(255, 230, 190), new Color(255, 140, 60)};

    /**
     * Produce the moment of checkmate: a crystal queen stands over the fallen king, lit by a
     * spotlight, with the rest of the game and a row of warm lights dissolving into the
     * background.
     */
    @Test
    void testCheckmate() {
        Scene scene = new Scene("Checkmate")
                .setBackground(new Color(4, 4, 6))
                .setAmbientLight(new AmbientLight(new Color(10, 10, 12)));
        addBoard(scene);

        addPiece(scene, Piece.QUEEN, 'e', 6, CRYSTAL);
        addPiece(scene, Piece.KING, 'c', 8, CRYSTAL);
        addPiece(scene, Piece.ROOK, 'h', 6, CRYSTAL);
        addPiece(scene, Piece.PAWN, 'b', 4, CRYSTAL);
        addPiece(scene, Piece.PAWN, 'f', 3, CRYSTAL);
        addFallenKing(scene, square('d', 5), new Vector(-1, 0, 0.35), SMOKED_GLASS);
        addPiece(scene, Piece.PAWN, 'f', 7, SMOKED_GLASS);
        addPiece(scene, Piece.PAWN, 'g', 7, SMOKED_GLASS);
        addPiece(scene, Piece.PAWN, 'a', 7, SMOKED_GLASS);
        addPiece(scene, Piece.PAWN, 'c', 5, SMOKED_GLASS);
        addPiece(scene, Piece.BISHOP, 'b', 7, SMOKED_GLASS);
        addPiece(scene, Piece.ROOK, 'f', 8, SMOKED_GLASS);

        // A warm spotlight on the queen and a cool rim light, each with a glowing softbox behind
        // it that shows up in reflections
        Point key = new Point(-560, 620, 380), rim = new Point(560, 420, -760);
        scene.lights.add(new SpotLight(new Color(1100, 980, 830), key, new Point(0, 40, -100).subtract(key))
                .setNarrowBeam(16).setSoftShadows(70, 2));
        scene.lights.add(new PointLight(new Color(260, 290, 380), rim).setSoftShadows(60, 2));
        addSoftbox(scene, key, 360, 220, new Color(255, 240, 220));
        addSoftbox(scene, rim, 120, 420, new Color(200, 220, 255));

        Point location = new Point(230, 72, 900);
        Point target = new Point(0, 88, -100);
        Point focus = new Point(0, 62, -100);
        double vpSize = 205, vpDistance = 600;
        addBokehLights(scene, location, target.subtract(location).normalize(), vpSize / vpDistance);

        Camera.getBuilder()
                .setRayTracer(scene, RayTracerType.ADAPTIVE_GRID)
                .setAdaptiveGridParameters(8, 11)
                .setLocation(location).setDirection(target)
                .setVpSize(vpSize, vpSize).setVpDistance(vpDistance)
                .setResolution(1200, 1200)
                .setAntiAliasing(9, new Jittered())
                .setDepthOfField(20, focus.subtract(location).dotProduct(target.subtract(location).normalize()))
                .setMultithreading(-2)
                .addPostProcessFilter(new BloomFilter().setThreshold(0.8f).setBlurRadius(17).setIntensity(0.35f))
                .setDebugPrint(0.1)
                .build()
                .renderImage()
                .writeToImage("chessCheckmate");
    }

    /**
     * Finds the center of a board square, at the height the pieces stand on.
     *
     * @param file the file, 'a' to 'h' from left to right
     * @param rank the rank, 1 (nearest the camera) to 8
     * @return the center of the square
     */
    private static Point square(char file, int rank) {
        return new Point(SQUARE * (file - 'a' - 3.5), LIFT, SQUARE * (4.5 - rank));
    }

    /**
     * Adds a standing piece.
     *
     * @param scene    the scene
     * @param piece    the piece
     * @param file     the file of its square
     * @param rank     the rank of its square
     * @param material its material
     */
    private static void addPiece(Scene scene, Piece piece, char file, int rank, Material material) {
        scene.geometries.add(ChessPieces.create(piece, square(file, rank), Vector.AXIS_Y, material));
    }

    /**
     * Adds a king lying on its side, resting on the rim of its base and the rim of its crown.
     *
     * @param scene     the scene
     * @param square    the square it lies on
     * @param direction the horizontal direction its crown points to
     * @param material  its material
     */
    private static void addFallenKing(Scene scene, Point square, Vector direction, Material material) {
        // The profile touches the board at the base rim (radius 38, height 5) and the crown rim
        // (radius 22.5, height 134), so the axis tilts down by the angle between them
        double tilt = Math.atan2(38 - 22.5, 134 - 5);
        Vector horizontal = new Vector(direction.getX(), 0, direction.getZ()).normalize();
        Vector axis = horizontal.scale(Math.cos(tilt)).add(Vector.AXIS_Y.scale(-Math.sin(tilt)));
        double axisHeight = 5 * Math.sin(tilt) + 38 * Math.cos(tilt) + LIFT;
        // Center the middle of the piece over the square
        double shift = 80 * Math.cos(tilt);
        Point base = new Point(square.getX() - horizontal.getX() * shift, axisHeight,
                square.getZ() - horizontal.getZ() * shift);
        scene.geometries.add(ChessPieces.create(Piece.KING, base, axis, material));
    }

    /**
     * Adds the board - 64 polished squares in a walnut frame - and the table under it.
     *
     * @param scene the scene
     */
    private static void addBoard(Scene scene) {
        Material light = new Material().setKd(new Double3(0.62, 0.58, 0.52)).setKs(0.35).setShininess(300).setKr(0.1);
        Material dark = new Material().setKd(new Double3(0.05, 0.045, 0.045)).setKs(0.5).setShininess(400).setKr(0.16);
        double half = 4 * SQUARE;
        for (int file = 0; file < 8; file++)
            for (int rank = 0; rank < 8; rank++) {
                double x = file * SQUARE - half, z = rank * SQUARE - half;
                scene.geometries.add(new Polygon(new Point(x, 0, z), new Point(x + SQUARE, 0, z),
                        new Point(x + SQUARE, 0, z + SQUARE), new Point(x, 0, z + SQUARE))
                        .setMaterial((file + rank) % 2 == 0 ? dark : light));
            }

        Material walnut = new Material().setKd(new Double3(0.30, 0.15, 0.07)).setKs(0.4).setShininess(200).setKr(0.08);
        double out = half + 45, bottom = -30;
        scene.geometries.add(
                // The frame around the squares
                new Polygon(new Point(-out, 0, -out), new Point(out, 0, -out), new Point(out, 0, -half),
                        new Point(-out, 0, -half)).setMaterial(walnut),
                new Polygon(new Point(-out, 0, half), new Point(out, 0, half), new Point(out, 0, out),
                        new Point(-out, 0, out)).setMaterial(walnut),
                new Polygon(new Point(-out, 0, -half), new Point(-half, 0, -half), new Point(-half, 0, half),
                        new Point(-out, 0, half)).setMaterial(walnut),
                new Polygon(new Point(half, 0, -half), new Point(out, 0, -half), new Point(out, 0, half),
                        new Point(half, 0, half)).setMaterial(walnut),
                // The sides of the board that face the camera
                new Polygon(new Point(-out, 0, out), new Point(out, 0, out), new Point(out, bottom, out),
                        new Point(-out, bottom, out)).setMaterial(walnut),
                new Polygon(new Point(out, 0, -out), new Point(out, 0, out), new Point(out, bottom, out),
                        new Point(out, bottom, -out)).setMaterial(walnut),
                new Polygon(new Point(-out, 0, -out), new Point(-out, 0, out), new Point(-out, bottom, out),
                        new Point(-out, bottom, -out)).setMaterial(walnut),
                // A dark, polished table
                new Plane(new Point(0, bottom, 0), Vector.AXIS_Y).setEmission(new Color(3, 3, 3))
                        .setMaterial(new Material().setKd(0.06).setKs(0.3).setShininess(100).setKr(0.1)));
    }

    /**
     * Adds a glowing panel behind a light, facing the board, so that glass and polish reflect
     * the light as a studio softbox.
     *
     * @param scene  the scene
     * @param light  the position of the light
     * @param width  the width of the panel
     * @param height the height of the panel
     * @param glow   the emission of the panel
     */
    private static void addSoftbox(Scene scene, Point light, double width, double height, Color glow) {
        Vector toBoard = Point.ZERO.subtract(light).normalize();
        Point center = light.add(toBoard.scale(-25));
        Vector right = toBoard.crossProduct(Vector.AXIS_Y).normalize().scale(width / 2);
        Vector up = right.crossProduct(toBoard).normalize().scale(height / 2);
        scene.geometries.add(new Polygon(center.add(right).add(up), center.add(right.scale(-1)).add(up),
                center.add(right.scale(-1)).add(up.scale(-1)), center.add(right).add(up.scale(-1)))
                .setEmission(glow).setMaterial(new Material().setKa(0)));
    }

    /**
     * Scatters small warm lights far behind the board, inside the camera's view, where depth of
     * field turns them into soft bokeh.
     *
     * @param scene    the scene
     * @param camera   the camera location
     * @param vTo      the unit viewing direction
     * @param viewSize the size of the view at unit distance
     */
    private static void addBokehLights(Scene scene, Point camera, Vector vTo, double viewSize) {
        Vector right = vTo.crossProduct(Vector.AXIS_Y).normalize();
        Vector up = right.crossProduct(vTo);
        Material glow = new Material().setKa(0);
        Random random = new Random(64);
        for (int i = 0; i < 32; i++) {
            double distance = 2700 + 1600 * random.nextDouble();
            double x = (random.nextDouble() - 0.5) * 1.3, y = -0.05 + 0.6 * random.nextDouble();
            Point center = camera.add(vTo.scale(distance)).add(right.scale(x * viewSize * distance))
                    .add(up.scale(y * viewSize * distance));
            // Lights below the table would be hidden anyway
            if (center.getY() < 40) continue;
            double strength = 0.8 + 1.4 * random.nextDouble();
            double radius = 25 + 30 * random.nextDouble();
            Color color = BOKEH_COLORS[random.nextInt(BOKEH_COLORS.length)];
            scene.geometries.add(new Sphere(center, radius).setEmission(color.scale(strength)).setMaterial(glow));
        }
    }
}
